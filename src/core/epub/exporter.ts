import * as cheerio from "cheerio";
import JSZip from "jszip";
import type { OutputMode } from "../types.js";
import { dirnamePosix, relativePosixPath, resolveZipPath } from "./container.js";
import {
  applyTranslationsToChapterXhtml,
  serializeUtf8Xml,
  type ChapterSegmentTranslation,
} from "./xhtml.js";

// Exported EPUBs must place an uncompressed `mimetype` entry first (STORE) per EPUB OCF spec
// and pass untouched binary assets through verbatim.
// See ADR 2026-11-24-epub-translator-architecture.

const BILINGUAL_CSS_FILENAME = "epub-translator-bilingual.css";
const BILINGUAL_CSS_CONTENT = `/* Generated by EPUB Translator — minimal bilingual reading styles */
.epub-tr-orig {
  margin-bottom: 0.35em;
  opacity: 0.78;
}
.epub-tr-zh {
  margin-top: 0.25em;
  margin-bottom: 1.05em;
  line-height: 1.72;
}
span.epub-tr-zh {
  display: inline-block;
  margin-top: 0.15em;
  margin-bottom: 0;
  font-weight: inherit;
}
`;

export interface ExportChapterInput {
  href: string;
  title: string;
  translatedTitle?: string | null;
  segments: ChapterSegmentTranslation[];
}

export interface ExportEpubOptions {
  sourceBuffer: Buffer | Uint8Array;
  opfPath: string;
  tocNcxPath?: string | null;
  navXhtmlPath?: string | null;
  outputMode: OutputMode;
  translatedTitle?: string | null;
  translatedDescription?: string | null;
  chapters: ExportChapterInput[];
}

function formatTitleByMode(original: string, translated: string | null | undefined, mode: OutputMode): string {
  const clean = translated?.trim();
  if (!clean) return original;
  if (mode === "translated_only") return clean;
  if (original.includes(clean)) return original;
  return `${clean} / ${original}`;
}

const XML_LOAD_OPTIONS = { xmlMode: true };

function updateOpfXml(
  opfXml: string,
  options: {
    outputMode: OutputMode;
    translatedTitle?: string | null;
    translatedDescription?: string | null;
    bilingualCssHref?: string;
  },
): string {
  const $ = cheerio.load(opfXml, XML_LOAD_OPTIONS);

  const findMetaEl = (localName: string) =>
    $("metadata *")
      .filter((_, el) => el.type === "tag" && (el.tagName.toLowerCase() === `dc:${localName}` || el.tagName.toLowerCase() === localName))
      .first();

  if (options.translatedTitle?.trim()) {
    const titleEl = findMetaEl("title");
    if (titleEl.length > 0) {
      titleEl.text(formatTitleByMode(titleEl.text().trim(), options.translatedTitle, options.outputMode));
    }
  }

  if (options.translatedDescription?.trim()) {
    const descEl = findMetaEl("description");
    if (descEl.length > 0) {
      descEl.text(formatTitleByMode(descEl.text().trim(), options.translatedDescription, options.outputMode));
    }
  }

  if (options.outputMode === "bilingual" && options.bilingualCssHref) {
    const manifest = $("manifest").first();
    const alreadyExists = manifest.find(`item[href="${options.bilingualCssHref}"]`).length > 0;
    if (manifest.length > 0 && !alreadyExists) {
      manifest.append(
        `\n    <item id="epub-translator-bilingual-css" href="${options.bilingualCssHref}" media-type="text/css"/>\n`,
      );
    }
  }

  return serializeUtf8Xml($);
}

function updateTocNcx(
  ncxXml: string,
  ncxDir: string,
  translatedTitleByHref: Map<string, string>,
  outputMode: OutputMode,
): string {
  const $ = cheerio.load(ncxXml, XML_LOAD_OPTIONS);
  $("navPoint").each((_, el) => {
    const src = $(el).children("content").first().attr("src")?.trim();
    if (!src) return;
    const resolved = resolveZipPath(ncxDir, src);
    const translated = translatedTitleByHref.get(resolved);
    if (!translated) return;
    const textEl = $(el).children("navLabel").children("text").first();
    if (textEl.length > 0) {
      textEl.text(formatTitleByMode(textEl.text().trim(), translated, outputMode));
    }
  });
  return serializeUtf8Xml($);
}

function updateNavXhtml(
  navXml: string,
  navDir: string,
  translatedTitleByHref: Map<string, string>,
  outputMode: OutputMode,
): string {
  const $ = cheerio.load(navXml, XML_LOAD_OPTIONS);
  $("nav a[href]").each((_, el) => {
    const href = $(el).attr("href")?.trim();
    if (!href) return;
    const resolved = resolveZipPath(navDir, href);
    const translated = translatedTitleByHref.get(resolved);
    if (!translated) return;
    const original = $(el).text().replace(/\s+/g, " ").trim();
    $(el).text(formatTitleByMode(original, translated, outputMode));
  });
  return serializeUtf8Xml($);
}

export async function exportTranslatedEpub(options: ExportEpubOptions): Promise<Buffer> {
  const sourceZip = await JSZip.loadAsync(options.sourceBuffer);
  const outZip = new JSZip();

  // 1. Write `mimetype` first with STORE (uncompressed) per EPUB OCF standard
  const mimeEntry = sourceZip.file("mimetype");
  const mimeContent = mimeEntry ? await mimeEntry.async("string") : "application/epub+zip";
  outZip.file("mimetype", mimeContent.trim(), { compression: "STORE" });

  const opfDir = dirnamePosix(options.opfPath);
  const bilingualCssPath = opfDir ? `${opfDir}/${BILINGUAL_CSS_FILENAME}` : BILINGUAL_CSS_FILENAME;

  const chapterMap = new Map<string, ExportChapterInput>();
  const translatedTitleByHref = new Map<string, string>();

  for (const ch of options.chapters) {
    chapterMap.set(ch.href, ch);
    if (ch.translatedTitle?.trim()) {
      translatedTitleByHref.set(ch.href, ch.translatedTitle.trim());
    }
  }

  // 2. Copy or transform all remaining entries
  const entryNames = Object.keys(sourceZip.files).filter((name) => name !== "mimetype");
  for (const name of entryNames) {
    const file = sourceZip.files[name];
    if (file.dir) continue;

    if (name === options.opfPath) {
      const originalOpf = await file.async("string");
      const updatedOpf = updateOpfXml(originalOpf, {
        outputMode: options.outputMode,
        translatedTitle: options.translatedTitle,
        translatedDescription: options.translatedDescription,
        bilingualCssHref: options.outputMode === "bilingual" ? BILINGUAL_CSS_FILENAME : undefined,
      });
      outZip.file(name, updatedOpf, { compression: "DEFLATE" });
      continue;
    }

    if (options.tocNcxPath && name === options.tocNcxPath) {
      const originalNcx = await file.async("string");
      const updatedNcx = updateTocNcx(
        originalNcx,
        dirnamePosix(options.tocNcxPath),
        translatedTitleByHref,
        options.outputMode,
      );
      outZip.file(name, updatedNcx, { compression: "DEFLATE" });
      continue;
    }

    if (options.navXhtmlPath && name === options.navXhtmlPath) {
      const originalNav = await file.async("string");
      const updatedNav = updateNavXhtml(
        originalNav,
        dirnamePosix(options.navXhtmlPath),
        translatedTitleByHref,
        options.outputMode,
      );
      outZip.file(name, updatedNav, { compression: "DEFLATE" });
      continue;
    }

    const chapter = chapterMap.get(name);
    if (chapter) {
      const originalXhtml = await file.async("string");
      const byDomPath = new Map(chapter.segments.map((s) => [s.domPath, s]));
      const cssHref =
        options.outputMode === "bilingual"
          ? relativePosixPath(dirnamePosix(name), bilingualCssPath)
          : undefined;
      const updatedXhtml = applyTranslationsToChapterXhtml(
        originalXhtml,
        byDomPath,
        options.outputMode,
        cssHref,
      );
      outZip.file(name, updatedXhtml, { compression: "DEFLATE" });
      continue;
    }

    // Untouched binary or ancillary asset — pass through verbatim
    const rawBytes = await file.async("uint8array");
    outZip.file(name, rawBytes, { compression: "DEFLATE" });
  }

  // 3. Inject bilingual stylesheet when needed
  if (options.outputMode === "bilingual") {
    outZip.file(bilingualCssPath, BILINGUAL_CSS_CONTENT, { compression: "DEFLATE" });
  }

  return outZip.generateAsync({ type: "nodebuffer" });
}
